  DOM, and a flat "0.6 em per character" estimate is nowhere near good enough
  once the result feeds axis gutters, legend item widths and label wrapping.
  These tables hold the advance width of each character in em (multiply by the
  font size to get pixels).

  Two families ship:

    * \`:arial\` (default) — Arial / Helvetica / Liberation Sans, the metrics
      shared by the overwhelming majority of UI sans stacks.
    * \`:dejavu\` — DejaVu Sans, what \`ui-sans-serif\` / \`system-ui\` resolves to
      on most Linux desktops and CI images.

  Pass \`chart: %{font_metrics: :arial | :dejavu | %{codepoint => em}}\` to pick
  one, or supply a measured table of your own. Characters missing from the
  table fall back to the table's average width.
  """

